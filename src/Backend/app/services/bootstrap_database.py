def _quote_identifier(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def _create_database_if_missing() -> str:
    target_url = make_url(settings.database_url)
    database_name = target_url.database

    if not database_name:
        raise RuntimeError("DATABASE_URL sem nome de banco de dados.")

    maintenance_url = target_url.set(database="postgres")
    maintenance_engine = create_engine(maintenance_url, isolation_level="AUTOCOMMIT", future=True)

    try:
        with maintenance_engine.connect() as connection:
            exists = connection.scalar(
                text("SELECT 1 FROM pg_database WHERE datname = :database_name"),
                {"database_name": database_name},
            )
            if exists is None:
                connection.execute(text(f"CREATE DATABASE {_quote_identifier(database_name)}"))
    finally:
        maintenance_engine.dispose()

    return database_name


def bootstrap_database() -> dict[str, int | str]:
    if not SEED_SQL_PATH.exists():
        raise RuntimeError(f"Arquivo de seed nao encontrado: {SEED_SQL_PATH}")

    database_name = _create_database_if_missing()
    seed_sql = (
        SEED_SQL_PATH.read_text(encoding="utf-8")
        .replace("\nBEGIN;\n", "\n")
        .replace("\nCOMMIT;", "")
    )
    target_engine = create_engine(settings.database_url, future=True)

    try:
        with target_engine.begin() as connection:
            connection.exec_driver_sql(SCHEMA_SQL)
            connection.exec_driver_sql(seed_sql)
    finally:
        target_engine.dispose()
        engine.dispose()

    return {
        "database": database_name,
        "clientes": 8,
        "salas": 7,
        "planos": 4,
        "assinaturas": 8,
        "reservas": 12,
        "avaliacoes": 5,
        "notificacoes": 5,
    }
